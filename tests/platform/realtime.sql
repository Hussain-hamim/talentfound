begin;
do $$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid(); c uuid:=gen_random_uuid(); m uuid:=gen_random_uuid(); p uuid:=gen_random_uuid(); inv uuid:=gen_random_uuid(); n uuid; rev bigint; cnt integer;
begin
 insert into auth.users(id,email,email_confirmed_at) values(a,a||'@example.test',now()),(b,b||'@example.test',now()),(outsider,outsider||'@example.test',now());
 insert into public.members(id,name) values(a,'Realtime sender'),(b,'Realtime recipient'),(outsider,'Realtime outsider');
 insert into public.accounts(id,email_notifications) values(a,false),(b,false),(outsider,false);
 insert into public.developer_profiles(id,handle,headline,location,timezone,skills) values(a,'qa-'||a,'Test','Test','UTC',array['TypeScript']);
 select revision into rev from public.realtime_signals where scope='discovery';
 insert into public.portfolio_projects(id,owner_id,title,published) values(p,a,'Private draft',false);
 if (select revision from public.realtime_signals where scope='discovery')<>rev then raise exception 'Draft leaked a public signal'; end if;
 update public.portfolio_projects set published=true where id=p;
 if (select revision from public.realtime_signals where scope='discovery')<=rev then raise exception 'Publish did not invalidate discovery'; end if;
 select revision into rev from public.realtime_signals where scope='discovery';
 delete from public.portfolio_projects where id=p;
 if (select revision from public.realtime_signals where scope='discovery')<=rev then raise exception 'Delete did not invalidate discovery'; end if;
 insert into public.conversations(id,member_a,member_b) values(c,least(a,b),greatest(a,b));
 insert into public.messages(id,conversation_id,sender_id,body) values(m,c,a,'A realtime message');
 select id into n from public.notifications where recipient_id=b and source_key='message:'||m;
 if n is null then raise exception 'Message notification missing'; end if;
 insert into public.messages(id,conversation_id,sender_id,body) values(m,c,a,'A realtime message') on conflict do nothing;
 if (select count(*) from public.notifications where recipient_id=b)<>1 then raise exception 'Duplicate notification'; end if;
 insert into public.conversation_reads(conversation_id,member_id,read_at) values(c,b,clock_timestamp());
 if (select read_at from public.notifications where id=n) is null then raise exception 'Conversation read did not clear notification'; end if;
 insert into public.invitations(id,conversation_id,sender_id,recipient_id,brief) values(inv,c,a,b,'{"title":"QA project"}');
 insert into public.messages(id,conversation_id,sender_id,body,invitation_id) values(gen_random_uuid(),c,a,'Please join',inv);
 if not exists(select 1 from public.notifications where recipient_id=b and kind='invitation') then raise exception 'Invitation notification missing'; end if;
 update public.invitations set status='accepted' where id=inv;
 if not exists(select 1 from public.notifications where recipient_id=a and kind='invitation_response') then raise exception 'Invitation response missing'; end if;
 insert into public.reviews(reviewer_id,developer_id,rating,body) values(b,a,5,'A helpful community review');
 if not exists(select 1 from public.notifications where recipient_id=a and kind='review') then raise exception 'Review notification missing'; end if;
 insert into public.review_replies(review_id,developer_id,body) select id,a,'Thank you!' from public.reviews where developer_id=a and reviewer_id=b;
 if not exists(select 1 from public.notifications where recipient_id=b and kind='review_reply') then raise exception 'Reply notification missing'; end if;
 perform set_config('request.jwt.claim.sub',b::text,true);
 set local role authenticated;
 select count(*) into cnt from public.notifications;
 if cnt<>3 then raise exception 'Recipient RLS failed: %',cnt; end if;
 update public.notifications set read_at=now() where read_at is null;
 begin
  update public.notifications set title='Forged';
  raise exception 'Notification content can be forged';
 exception when insufficient_privilege then null;
 end;
 if exists(select 1 from public.realtime_signals where owner_id is not null and owner_id<>b) then raise exception 'Private signal leaked'; end if;
 reset role;
 perform set_config('request.jwt.claim.sub',outsider::text,true);
 set local role authenticated;
 if exists(select 1 from public.notifications) then raise exception 'Unrelated account read notifications'; end if;
 reset role;
 insert into public.blocks(owner_id,blocked_id) values(b,a);
 perform set_config('request.jwt.claim.sub',b::text,true);
 set local role authenticated;
 if exists(select 1 from public.notifications) then raise exception 'Blocked notification visible'; end if;
 reset role;
 select count(*) into cnt from public.notifications where recipient_id=b;
 insert into public.messages(id,conversation_id,sender_id,body) values(gen_random_uuid(),c,a,'Blocked test');
 if (select count(*) from public.notifications where recipient_id=b)<>cnt then raise exception 'Blocked notification generated'; end if;
 perform set_config('request.jwt.claim.sub','',true);
 set local role anon;
 if exists(select 1 from public.realtime_signals where owner_id is not null) then raise exception 'Guest private signal leak'; end if;
 reset role;
end $$;
rollback;
